async fn get_default_player_name(session: &Session, ctx: &Context) -> String {
    let Some(user_id) = session.user_id else {
        return "Player{NUMBER}".to_string();
    };
    let mut conn = ctx.db_pool.get().await.unwrap();
    let Ok(Some(username)) = get_username(user_id, &mut conn).await else {
        return "Player{NUMBER}".to_string();
    };
    let truncated = username.chars().take(14).collect::<String>();
    format!("{}{{NUMBER}}", truncated)
}

/// Option definitions never change for a given apworld version, the expiry is there to shed the
/// ones nobody asks for anymore and to pick up fixes to the generator within a day.
const OPTIONS_CACHE_TTL_SECS: u64 = 24 * 3600;

/// The option definitions generated by the workers, kept in Valkey.
///
/// They can't live in the memory of a lobby process: a worker reports a finished job to
/// whichever lobby process its connection is on, and the request waiting for that job may be
/// served by another one.
///
/// A definition belongs to the Archipelago version, the base, whose worker generated it: the
/// same release of a world can have other options, or none, on another base.
#[derive(Clone)]
pub struct OptionsCache {
    redis_pool: RedisPool,
    legacy_base: Version,
}

impl OptionsCache {
    /// `legacy_base` is the base whose definitions keep the keys they had before definitions
    /// had a base: every definition from then was generated on it.
    pub fn new(redis_pool: RedisPool, legacy_base: Version) -> Self {
        Self {
            redis_pool,
            legacy_base,
        }
    }

    pub fn legacy_base(&self) -> &Version {
        &self.legacy_base
    }

    fn key(&self, base: &Version, apworld_name: &str, version: &Version) -> String {
        if base == &self.legacy_base {
            format!("options_def:{apworld_name}:{version}")
        } else {
            format!("options_def:base:{base}:{apworld_name}:{version}")
        }
    }

    pub async fn get(
        &self,
        base: &Version,
        apworld_name: &str,
        version: &Version,
    ) -> anyhow::Result<Option<OptionsDef>> {
        let mut redis = self.redis_pool.get().await?;
        let stored: Option<Vec<u8>> = redis.get(self.key(base, apworld_name, version)).await?;
        let Some(stored) = stored else {
            return Ok(None);
        };

        match decode_options_def(&stored) {
            Ok(options) => Ok(Some(options)),
            Err(e) => {
                // Written by a lobby with another idea of what definitions look like
                tracing::warn!(%base, %apworld_name, %version, %e, "Ignoring unreadable option definitions");
                Ok(None)
            }
        }
    }

    pub async fn contains(
        &self,
        base: &Version,
        apworld_name: &str,
        version: &Version,
    ) -> anyhow::Result<bool> {
        let mut redis = self.redis_pool.get().await?;

        Ok(redis.exists(self.key(base, apworld_name, version)).await?)
    }

    pub async fn insert(
        &self,
        base: &Version,
        apworld_name: &str,
        version: &Version,
        options: &OptionsDef,
    ) -> anyhow::Result<()> {
        let mut redis = self.redis_pool.get().await?;
        redis
            .set_ex::<_, _, ()>(
                self.key(base, apworld_name, version),
                encode_options_def(options)?,
                OPTIONS_CACHE_TTL_SECS,
            )
            .await?;

        Ok(())
    }
}

// Definitions are mostly lists of item and location names repeated across options. They
// average 140kB as JSON and compress to an eighth of that.
fn encode_options_def(options: &OptionsDef) -> anyhow::Result<Vec<u8>> {
    let mut encoder = GzEncoder::new(Vec::new(), Compression::default());
    serde_json::to_writer(&mut encoder, options)?;

    Ok(encoder.finish()?)
}

fn decode_options_def(stored: &[u8]) -> anyhow::Result<OptionsDef> {
    Ok(serde_json::from_reader(GzDecoder::new(stored))?)
}

