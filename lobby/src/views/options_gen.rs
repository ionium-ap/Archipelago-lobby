#[derive(FromForm)]
struct YamlUpload<'a> {
    yaml: &'a str,
}

fn validate_option_value(value: &serde_json::Value, option_def: &crate::jobs::OptionDef) -> bool {
    // For weighted options, only validate non-zero weighted values
    if let Some(obj) = value.as_object() {
        return obj
            .iter()
            .filter(|(_, v)| v.as_i64().map(|n| n != 0).unwrap_or(true))
            .all(|(k, _)| validate_single_value(k, option_def));
    }

    if let Some(s) = value.as_str() {
        return validate_single_value(s, option_def);
    }
    if let Some(n) = value.as_i64() {
        return validate_numeric_value(n, option_def);
    }
    if let Some(arr) = value.as_array() {
        if !option_def.has_valid_keys() {
            return true;
        }
        let valid_keys = option_def.valid_keys();
        return arr.iter().all(|v| {
            v.as_str()
                .map(|s| valid_keys.iter().any(|k| k == s))
                .unwrap_or(true)
        });
    }
    true
}

fn validate_single_value(value: &str, option_def: &crate::jobs::OptionDef) -> bool {
    // "random", "random-low", "random-high", etc. are always valid
    if value.starts_with("random") {
        return true;
    }

    match option_def.ty.as_str() {
        "choice" => option_def
            .choices
            .as_ref()
            .map(|c| c.iter().any(|choice| choice == value))
            .unwrap_or(true),
        "text_choice" => option_def
            .suggestions
            .as_ref()
            .map(|s| s.iter().any(|sug| sug == value))
            .unwrap_or(true),
        "named_range" => {
            if let Some(suggestions) = &option_def.suggestions {
                if suggestions.iter().any(|s| s == value) {
                    return true;
                }
            }
            if let Ok(n) = value.parse::<i64>() {
                return validate_numeric_value(n, option_def);
            }
            false
        }
        _ => true,
    }
}

fn validate_numeric_value(value: i64, option_def: &crate::jobs::OptionDef) -> bool {
    match option_def.ty.as_str() {
        "range" | "named_range" => {
            if let Some((min, max)) = option_def.range {
                value >= min && value <= max
            } else {
                true
            }
        }
        _ => true,
    }
}

#[rocket::post("/options/edit?<base>", data = "<form>")]
#[tracing::instrument(skip(options_gen_queue, options_cache, index_manager, ctx, session, form))]
async fn edit_yaml<'a>(
    base: Option<&str>,
    form: Form<YamlUpload<'a>>,
    options_gen_queue: &State<OptionsGenQueue>,
    options_cache: &State<OptionsCache>,
    index_manager: &'a State<IndexManager>,
    ctx: &'a State<Context>,
    redirect_to: &RedirectTo,
    session: Session,
    lobby_config: &State<LobbyConfig>,
) -> Result<OptionsTpl<'a>> {
    redirect_to.set("/options");

    let yaml: serde_json::Value =
        serde_saphyr::from_str(form.yaml).map_err(|e| anyhow!("Failed to parse YAML: {}", e))?;

    let player_name = yaml
        .get("name")
        .and_then(|v| v.as_str())
        .map(|s| s.to_string());

    let description = yaml
        .get("description")
        .and_then(|v| v.as_str())
        .map(|s| s.to_string());

    let game_field = yaml
        .get("game")
        .ok_or_else(|| anyhow!("YAML is missing 'game' field"))?;

    let game_name = if let Some(s) = game_field.as_str() {
        s.to_string()
    } else if game_field.is_object() {
        return Err(anyhow!(
            "Weighted game randomizers are not supported. Please use a YAML with a single game."
        )
        .into());
    } else {
        return Err(anyhow!("Invalid 'game' field in YAML").into());
    };

    let base = requested_base(index_manager, base).await?;
    let index = index_manager.index_for(&base).await?;
    let (apworld_name, latest_version, display_name) = index
        .worlds
        .iter()
        .find(|(_, world)| world.name == game_name)
        .map(|(name, world)| {
            let latest = world.versions.keys().max().unwrap().clone();
            (name.clone(), latest, world.display_name.clone())
        })
        .ok_or_else(|| anyhow!("Game '{}' not found", game_name))?;

    let mut apworlds: Vec<(String, String)> = index
        .worlds
        .iter()
        .map(|(apworld_name, world)| (apworld_name.clone(), world.display_name.clone()))
        .collect();
    apworlds.sort_by_key(|(_, world_name)| world_name.to_lowercase());

    let versions: Vec<String> = index
        .worlds
        .get(&apworld_name)
        .unwrap()
        .versions
        .keys()
        .map(|v| v.to_string())
        .rev()
        .collect();
    drop(index);

    let options = get_options_def(
        &apworld_name,
        &latest_version,
        &base,
        options_gen_queue,
        options_cache,
    )
    .await?;

    let option_defs: HashMap<&String, &crate::jobs::OptionDef> = options
        .iter()
        .flat_map(|(_, group_options)| group_options.iter())
        .collect();

    let game_options = yaml.get(&game_name).and_then(|v| v.as_object());

    let mut prefilled_values: HashMap<String, serde_json::Value> = HashMap::new();
    let mut warnings: Vec<String> = vec![];
    let mut yaml_option_names: HashSet<String> = HashSet::new();
    let mut outdated_values: HashSet<String> = HashSet::new();

    if let Some(game_opts) = game_options {
        for (key_str, value) in game_opts {
            yaml_option_names.insert(key_str.clone());

            let Some(option_def) = option_defs.get(key_str) else {
                warnings.push(key_str.clone());
                continue;
            };

            let is_weighted_type = WEIGHTED_TYPES.contains(&option_def.ty.as_str());
            if value.is_object()
                && option_def.ty != "counter"
                && option_def.ty != "dict"
                && !is_weighted_type
            {
                warnings.push(format!(
                    "{} (weighted options not supported for this type)",
                    key_str
                ));
                continue;
            }

            let coalesced = value.as_object().and_then(|mapping| {
                if !is_weighted_type {
                    return None;
                }
                let non_zero: Vec<_> = mapping
                    .iter()
                    .filter(|(_, v)| v.as_i64().map(|n| n != 0).unwrap_or(true))
                    .collect();
                if non_zero.len() == 1 {
                    Some(serde_json::Value::String(non_zero[0].0.clone()))
                } else {
                    None
                }
            });

            let json_value = coalesced.unwrap_or_else(|| value.clone());

            if option_def.is_editable() && !validate_option_value(&json_value, option_def) {
                outdated_values.insert(key_str.clone());
                // If invalid, don't insert it in prefill so it gets reset
                continue;
            }

            prefilled_values.insert(key_str.clone(), json_value);
        }
    }

    // If we have a prefilled player name, then the default doesn't matter since it won't be used
    let default_player_name = match &player_name {
        Some(_) => "Player{NUMBER}".to_string(),
        None => get_default_player_name(&session, ctx).await,
    };
    let base_options = selectable_bases(index_manager, &base).await;
    let base_query = base_query(index_manager, &base).await;

    Ok(OptionsTpl {
        base: TplContext::from_session(
            "options",
            session,
            ctx,
            lobby_config,
            Some(format!("Options Generator - {}", display_name)),
        )
        .await,
        apworlds,
        versions,
        selected_apworld: Some(apworld_name),
        selected_version: Some(latest_version.to_string()),
        options: Some(options),
        warnings,
        prefilled_values: Some(prefilled_values),
        prefilled_player_name: player_name,
        prefilled_description: description,
        yaml_option_names,
        outdated_values,
        default_player_name,
        base_query,
        base_options,
    })
}

#[rocket::post("/options/<apworld_name>/<version>/download?<base>", data = "<form>")]
#[tracing::instrument(skip(host, index_manager, form, options_gen_queue, options_cache))]
async fn download_yaml<'a>(
    apworld_name: &str,
    version: &str,
    base: Option<&str>,
    host: &Host<'_>,
    form: Form<HashMap<String, String>>,
    index_manager: &State<IndexManager>,
    options_gen_queue: &State<OptionsGenQueue>,
    options_cache: &State<OptionsCache>,
) -> ApiResult<YamlDownload<'a>> {
    // The page fetches this and saves whatever comes back, so a failure has to be an error
    // status with its message as the body. A redirect would get followed and saved as the YAML.
    let not_found = |message: &'static str| ApiError {
        error: anyhow!(message),
        status: Status::NotFound,
    };

    let parsed_version = Version::from_str(version).map_err(|_| not_found("Invalid version"))?;
    let base = requested_base(index_manager, base)
        .await
        .map_err(|_| not_found("Unknown Archipelago version"))?;
    let game_name = {
        let index = index_manager.index_for(&base).await?;
        let Some(apworld) = index.worlds.get(apworld_name) else {
            return Err(not_found("Unknown apworld"));
        };
        if !apworld.versions.contains_key(&parsed_version) {
            return Err(not_found("Unknown version for this apworld"));
        }
        apworld.name.clone()
    };

    let options = get_options_def(
        apworld_name,
        &parsed_version,
        &base,
        options_gen_queue,
        options_cache,
    )
    .await
    .status(Status::ServiceUnavailable)?;

    let player_name = form.get("player").map(|s| s.as_str()).unwrap_or("Player");
    let player_name = if player_name.is_empty() {
        "Player"
    } else {
        player_name
    };

    let options_query = base_query(index_manager, &base).await;
    let description = form
        .get("description")
        .filter(|s| !s.is_empty())
        .cloned()
        .unwrap_or_else(|| {
            format!("Generated on https://{host}/options/{apworld_name}{options_query}")
        });

    // Build game options in definition order
    let mut game_options: IndexMap<String, serde_json::Value> = IndexMap::new();
    for (_group_name, group_options) in options.iter() {
        for (option_name, _option_def) in group_options.iter() {
            if let Some(value) = form.get(option_name) {
                // Try to parse as JSON for complex types (lists, counters, bools, numbers)
                let parsed = serde_json::from_str::<serde_json::Value>(value)
                    .unwrap_or_else(|_| serde_json::Value::String(value.clone()));
                game_options.insert(option_name.clone(), parsed);
            }
        }
    }

    // Build the full YAML structure
    let mut root: IndexMap<String, serde_json::Value> = IndexMap::new();
    root.insert(
        "game".to_string(),
        serde_json::Value::String(game_name.clone()),
    );
    root.insert(
        "name".to_string(),
        serde_json::Value::String(player_name.to_string()),
    );
    root.insert(
        "description".to_string(),
        serde_json::Value::String(description),
    );
    root.insert(game_name.clone(), serde_json::to_value(&game_options)?);

    let yaml = serde_saphyr::to_string(&root)?;

    let value = format!("attachment; filename=\"{}.yaml\"", player_name);
    Ok(YamlDownload {
        content: yaml,
        headers: Header::new(CONTENT_DISPOSITION.as_str(), value),
    })
}

pub fn routes() -> Vec<Route> {
    rocket::routes![
        options_apworld_versions,
        options_gen_api,
        options_gen,
        edit_yaml,
        download_yaml,
    ]
}

// These need a `valkey-server` binary in the PATH, like the tests of the `wq` crate
#[cfg(test)]
mod tests {
    use super::*;
    use crate::jobs::{get_options_gen_callback, OptionDef, OptionsGenResponse};
    use crate::test_utils::{redis_pool, start_valkey, ValkeyInstance};

    const LEGACY: Version = Version::new(0, 6, 7);
    const NEWER: Version = Version::new(0, 6, 8);

    /// What one lobby process holds of the options generator
    async fn lobby_process(valkey: &ValkeyInstance) -> (OptionsGenQueue, OptionsCache) {
        let cache = OptionsCache::new(redis_pool(valkey), LEGACY);
        let queue = OptionsGenQueue::builder("options_gen")
            .with_default_partition("0.6.7")
            .with_callback(get_options_gen_callback(cache.clone()))
            .build(&valkey.url())
            .await
            .unwrap();

        (queue, cache)
    }

    fn test_options() -> OptionsDef {
        let option = OptionDef {
            default: serde_json::json!("normal"),
            description: "How hard the game is".to_string(),
            ty: "choice".to_string(),
            display_name: "Difficulty".to_string(),
            range: None,
            choices: Some(vec!["easy".to_string(), "normal".to_string()]),
            suggestions: None,
            valid_keys: None,
        };

        IndexMap::from([(
            "Game Options".to_string(),
            IndexMap::from([("difficulty".to_string(), option)]),
        )])
    }

    fn as_json(options: &OptionsDef) -> serde_json::Value {
        serde_json::to_value(options).unwrap()
    }

    #[rocket::async_test]
    async fn test_definitions_reach_a_process_that_did_not_get_the_result() {
        let valkey = start_valkey();
        let (asking_queue, asking_cache) = lobby_process(&valkey).await;
        let (resolving_queue, _resolving_cache) = lobby_process(&valkey).await;

        // The worker reports to the other process than the one serving the request
        let worker = rocket::tokio::spawn(async move {
            let job = loop {
                if let Some(job) = resolving_queue.claim_job("worker").await.unwrap() {
                    break job;
                }
            };
            let response = OptionsGenResponse {
                options: test_options(),
                error: None,
            };
            // Resolved at once, which a real worker never does: the result is then gone before
            // the process that asked has started waiting for it, and it must still be told.
            resolving_queue
                .resolve_job("worker", job.job_id, JobStatus::Success, Some(response))
                .await
                .unwrap();
        });

        let options = get_options_def(
            "world",
            &Version::new(1, 0, 0),
            &LEGACY,
            State::from(&asking_queue),
            State::from(&asking_cache),
        )
        .await
        .expect("The definitions should be available to the process that asked for them");
        worker.await.unwrap();

        assert_eq!(as_json(&options), as_json(&test_options()));
    }

    #[rocket::async_test]
    async fn test_cached_definitions_need_no_job() {
        let valkey = start_valkey();
        let (queue, cache) = lobby_process(&valkey).await;
        let version = Version::new(1, 0, 0);
        assert!(!cache.contains(&LEGACY, "world", &version).await.unwrap());

        cache
            .insert(&LEGACY, "world", &version, &test_options())
            .await
            .unwrap();

        assert!(cache.contains(&LEGACY, "world", &version).await.unwrap());
        // Nothing serves the queue here, so this only returns if the cache answers
        let options = get_options_def(
            "world",
            &version,
            &LEGACY,
            State::from(&queue),
            State::from(&cache),
        )
        .await
        .unwrap();
        assert_eq!(as_json(&options), as_json(&test_options()));
        assert!(cache
            .get(&LEGACY, "world", &Version::new(2, 0, 0))
            .await
            .unwrap()
            .is_none());
    }

    #[rocket::async_test]
    async fn test_unreadable_definitions_are_a_miss() {
        let valkey = start_valkey();
        let pool = redis_pool(&valkey);
        let cache = OptionsCache::new(pool.clone(), LEGACY);
        let version = Version::new(1, 0, 0);
        let mut redis = pool.get().await.unwrap();
        redis
            .set::<_, _, ()>(cache.key(&LEGACY, "world", &version), "not gzip")
            .await
            .unwrap();

        assert!(cache
            .get(&LEGACY, "world", &version)
            .await
            .unwrap()
            .is_none());
    }

    fn other_options() -> OptionsDef {
        let mut options = test_options();
        options.insert("Only On The Newer Base".to_string(), IndexMap::new());

        options
    }

    #[rocket::async_test]
    async fn test_definitions_of_two_bases_are_kept_apart() {
        let valkey = start_valkey();
        let (_queue, cache) = lobby_process(&valkey).await;
        let version = Version::new(1, 0, 0);

        cache
            .insert(&LEGACY, "world", &version, &test_options())
            .await
            .unwrap();
        assert!(!cache.contains(&NEWER, "world", &version).await.unwrap());

        cache
            .insert(&NEWER, "world", &version, &other_options())
            .await
            .unwrap();

        let legacy = cache.get(&LEGACY, "world", &version).await.unwrap();
        assert_eq!(as_json(&legacy.unwrap()), as_json(&test_options()));
        let newer = cache.get(&NEWER, "world", &version).await.unwrap();
        assert_eq!(as_json(&newer.unwrap()), as_json(&other_options()));
    }

    #[rocket::async_test]
    async fn test_legacy_base_keeps_the_keys_from_before_bases() {
        let valkey = start_valkey();
        let pool = redis_pool(&valkey);
        let cache = OptionsCache::new(pool.clone(), LEGACY);
        let version = Version::new(1, 0, 0);

        // What a lobby from before definitions had a base stored, and still reads
        let mut redis = pool.get().await.unwrap();
        redis
            .set::<_, _, ()>(
                "options_def:world:1.0.0",
                encode_options_def(&test_options()).unwrap(),
            )
            .await
            .unwrap();

        let found = cache.get(&LEGACY, "world", &version).await.unwrap();
        assert_eq!(as_json(&found.unwrap()), as_json(&test_options()));
        assert!(cache
            .get(&NEWER, "world", &version)
            .await
            .unwrap()
            .is_none());

        cache
            .insert(&NEWER, "world", &version, &other_options())
            .await
            .unwrap();
        let mut keys: Vec<String> = redis.keys("options_def:*").await.unwrap();
        keys.sort();
        assert_eq!(
            keys,
            [
                "options_def:base:0.6.8:world:1.0.0",
                "options_def:world:1.0.0"
            ]
        );
    }

    /// A worker for `base` that takes one job and answers it with `options`
    fn worker(
        queue: OptionsGenQueue,
        base: &'static str,
        options: OptionsDef,
    ) -> rocket::tokio::task::JoinHandle<Option<Version>> {
        rocket::tokio::spawn(async move {
            let job = loop {
                if let Some(job) = queue.claim_job_in(Some(base), "worker").await.unwrap() {
                    break job;
                }
            };
            let response = OptionsGenResponse {
                options,
                error: None,
            };
            queue
                .resolve_job("worker", job.job_id, JobStatus::Success, Some(response))
                .await
                .unwrap();

            job.params.ap_version
        })
    }

    #[rocket::async_test]
    async fn test_definitions_are_generated_by_the_base_they_are_for() {
        let valkey = start_valkey();
        let (asking_queue, cache) = lobby_process(&valkey).await;
        let (legacy_queue, _) = lobby_process(&valkey).await;
        let (newer_queue, _) = lobby_process(&valkey).await;
        let version = Version::new(1, 0, 0);

        // Both workers wait. Only the one for the base that is asked for gets the job.
        let legacy_worker = worker(legacy_queue, "0.6.7", test_options());
        let newer_worker = worker(newer_queue, "0.6.8", other_options());

        let options = get_options_def(
            "world",
            &version,
            &NEWER,
            State::from(&asking_queue),
            State::from(&cache),
        )
        .await
        .unwrap();
        assert_eq!(as_json(&options), as_json(&other_options()));
        assert_eq!(newer_worker.await.unwrap(), Some(NEWER));
        assert!(!cache.contains(&LEGACY, "world", &version).await.unwrap());

        let options = get_options_def(
            "world",
            &version,
            &LEGACY,
            State::from(&asking_queue),
            State::from(&cache),
        )
        .await
        .unwrap();
        assert_eq!(as_json(&options), as_json(&test_options()));
        assert_eq!(legacy_worker.await.unwrap(), Some(LEGACY));
    }

    #[rocket::async_test]
    async fn test_job_from_before_bases_is_stored_for_the_legacy_base() {
        let valkey = start_valkey();
        let (queue, cache) = lobby_process(&valkey).await;
        let params = OptionsGenParams {
            apworld: ("world".to_string(), Version::new(1, 0, 0)),
            otlp_context: HashMap::new(),
            ap_version: None,
        };
        queue
            .enqueue_job(&params, wq::Priority::Low, Duration::from_secs(30))
            .await
            .unwrap();

        worker(queue, "0.6.7", test_options()).await.unwrap();

        assert!(cache
            .contains(&LEGACY, "world", &Version::new(1, 0, 0))
            .await
            .unwrap());
    }
}
